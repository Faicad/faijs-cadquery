// upstream expression:
//   f1 = plane(1, 1) - face(circle(0.1))
//   f2 = (plane(2, 2) - face(circle(0.1))).moved(z=1)
//   res = loft(f1, f2, history=h)
// — a 1x1 -> 2x2 frustum with a straight r=0.1 cylindrical hole through it.
//
// CAPTURE (plan §5, one-shot python against cadquery 2.8.0):
//   plane(1, 1)                          = Face f1/e4/w1/v4, bbox x[-0.5,0.5] y[-0.5,0.5] z[0,0]
//   face(circle(0.1))                    = Face f1/e1/w1/v1, vol 0.0314159265358979
//   f1 = plane(1,1) - face(circle(0.1))  = Face f1/e5/w2/v5, vol 0.968584073464102
//   f2                                   = Face f1/e5/w2/v5, vol 3.9685840734641 (z=1)
//   res                                  = Solid f7/e15/w9/v10
//                                          bbox x/y[-1.0000001,1.0000001] z[-1e-7,1.0000001]
//                                          vol 2.30191740679744  (= 7/3 - pi*0.01)
//
// `plane(w, l)` is a FINITE w x l face (BRepBuilderAPI_MakeFace(gp_Pln(O,+Z),
// -w/2, w/2, -l/2, l/2)) — NOT the unbounded gp_Pln face the port plan assumed.
// The 1e-7 bbox slack is generated by BRepOffsetAPI_ThruSections itself
// (loft(plane(1,1), plane(2,2)) has it too), not by the inputs.
//
// Same construction as the already-ported test_loft__r6: upstream lofts the
// outer wires into a capped solid, lofts each inner-wire pair into its own
// capped solid, then sews them together (`solid(side, *sides, top, bot)` with
// `top -= compound(tops)`), which is exactly the boolean difference of the
// capped solids. So: outer(rect 1x1 -> rect 2x2) - inner(circle 0.1 -> circle 0.1).
// ref anchor: vol 2.30191740680, com (-3.4e-17, 6.8e-17, 0.608605112964),
//             bbox x +-1.0000001 y +-1.0000001 z[-1e-7, 1.0000001], topo f7/e15/v10/s1
import * as cq from '@faicad/faijs-cadquery'
// outer: rect(1, 1) @z=0 -> rect(2, 2) @z=1
let a0 = await cq.rect(cq.Workplane('XY'), 1, 1)
let pa1 = await cq.transformed(cq.Workplane('XY'), { offset: [0, 0, 1] })
let a1 = await cq.rect(pa1, 2, 2)
let outer = await cq.loft(a0, a1)
// inner: circle(0.1) @z=0 -> circle(0.1) @z=1
let b0 = await cq.circle(cq.Workplane('XY'), 0.1)
let pb1 = await cq.transformed(cq.Workplane('XY'), { offset: [0, 0, 1] })
let b1 = await cq.circle(pb1, 0.1)
let inner = await cq.loft(b0, b1)
// res = outer - inner
let res = await cq.cut(outer, inner)
let result = cq.val(res)
